// Helper to generate simulated candle history
export function generateCandleHistory(
  basePrice: number,
  trend: 'up' | 'down' | 'volatile' = 'up',
  count: number = 30
): CandlePoint[] {
  const candles: CandlePoint[] = [];
  let currentPrice = basePrice * (trend === 'up' ? 0.92 : trend === 'down' ? 1.08 : 0.98);
  const now = new Date('2026-09-28T09:30:00Z');

  for (let i = 0; i < count; i++) {
    const time = new Date(now.getTime() - (count - 1 - i) * 24 * 3600 * 1000);
    const dateStr = time.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });

    const bias = trend === 'up' ? 0.004 : trend === 'down' ? -0.004 : 0.001;
    const randomPct = (Math.random() - 0.48 + bias) * 0.025;
    const open = currentPrice;
    const close = Math.max(open * 0.7, open * (1 + randomPct));
    const high = Math.max(open, close) * (1 + Math.random() * 0.008);
    const low = Math.min(open, close) * (1 - Math.random() * 0.008);
    const volume = Math.floor(Math.random() * 45000000 + 10000000);

    candles.push({
      time: dateStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentPrice = close;
  }
  // Ensure the last close matches roughly basePrice
  if (candles.length > 0) {
    candles[candles.length - 1].close = basePrice;
  }
  return candles;
}

